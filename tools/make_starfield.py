#!/usr/bin/env python3
"""Pack the Yale Bright Star Catalogue into app/js/vendor/bsc5.js.

    python tools/make_starfield.py BSC5_DAT

BSC5_DAT is the fixed-width catalog file of the Yale Bright Star Catalogue,
5th revised edition (Hoffleit & Warren 1991; CDS/ADC catalog V/50, file
"catalog"/bsc5.dat): 9110 entries, J2000 positions. Entries without a
position (novae / removed objects) are skipped.

Output: SAT.bsc5 = {n, data} where data is base64 of little-endian 16-bit
quadruples per star — RA*100 (uint16, degrees), Dec*100 (int16, degrees),
V*100 (int16), (B-V)*1000 (int16, -32768 = unknown). Brightest first.
"""
import base64
import pathlib
import struct
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "app/js/vendor/bsc5.js"
NO_BV = -32768


def parse(path):
    stars = []
    for line in open(path, encoding="latin-1"):
        line = line.rstrip("\n").ljust(114)
        ra_h, ra_m, ra_s = line[75:77], line[77:79], line[79:83]
        if not (ra_s.strip() and line[83] in "+-" and line[84:90].strip()):
            continue   # removed entry (nova, cluster, galaxy): no position
        ra = (int(ra_h) + int(ra_m) / 60 + float(ra_s) / 3600) * 15
        dec = int(line[84:86]) + int(line[86:88]) / 60 + int(line[88:90]) / 3600
        if line[83] == "-":
            dec = -dec
        vmag = line[102:107].strip()
        if not vmag:
            continue
        bv = line[109:114].strip()
        stars.append((ra, dec, float(vmag), float(bv) if bv else None, line[0:4].strip()))
    return stars


def main():
    stars = parse(sys.argv[1])
    stars.sort(key=lambda s: s[2])
    by_hr = {s[4]: s for s in stars}
    # sanity: Sirius (HR 2491), Vega (HR 7001), Polaris (HR 424), Betelgeuse (HR 2061)
    for hr, (ra, dec, v) in {"2491": (101.29, -16.72, -1.46), "7001": (279.23, 38.78, 0.03),
                             "424": (37.95, 89.26, 2.02), "2061": (88.79, 7.41, 0.50)}.items():
        s = by_hr[hr]
        assert abs(s[0] - ra) < 0.05 and abs(s[1] - dec) < 0.05 and abs(s[2] - v) < 0.06, (hr, s)
    buf = bytearray()
    for ra, dec, v, bv, _ in stars:
        buf += struct.pack("<Hhhh", round(ra * 100) % 36000, round(dec * 100), round(v * 100),
                           NO_BV if bv is None else round(bv * 1000))
    data = base64.b64encode(bytes(buf)).decode("ascii")
    OUT.write_text(
        "/* Yale Bright Star Catalogue, 5th rev. ed. (Hoffleit & Warren 1991;\n"
        " * CDS/ADC catalog V/50): J2000 RA/Dec, V magnitude, B-V colour index.\n"
        " * Generated by tools/make_starfield.py — base64 of little-endian 16-bit\n"
        " * quadruples per star, brightest first: RA*100 (uint16, deg),\n"
        " * Dec*100 (int16, deg), V*100 (int16), (B-V)*1000 (int16, -32768 = n/a). */\n"
        f"SAT.bsc5 = {{ n: {len(stars)}, data: '{data}' }};\n")
    print(f"{len(stars)} stars, V {stars[0][2]} .. {stars[-1][2]}, "
          f"{sum(1 for s in stars if s[3] is None)} without B-V -> {OUT} "
          f"({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
